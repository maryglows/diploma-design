  const title=n=>s[n-1].shapes.getItem('slide-title');
  if(String(title(27).text)!=='Дерево и внешний вид'||String(title(28).text)!=='Варианты формы для сравнения')
    throw Error('The reviewed slides have changed; inspect before editing');
  let changes=0;
